#!/usr/bin/env bash
# Fails on assets that nothing uses (#320). A file under assets/ is used when its res:// path is
# named in a script, scene, resource, content file or the project settings; when a used glTF names
# it as one of its buffers or images; or when it's a texture Godot's import extracted from a used
# model next to it (named `<model>_<image>`, its .import carrying the generating importer's
# parameters). Each pack's own notes (SOURCE.md, its license) and Godot's .import files are left
# out: they come with the files they describe. Asset paths keep to letters, digits and `._/-`, so
# a path is always matched whole.
# Usage: tools/checks/unused_assets.sh (from the repository's root)
set -euo pipefail

named=$(mktemp)
trap 'rm -f "$named"' EXIT

assets=$(git ls-files assets | { grep -vE '\.import$|/SOURCE\.md$|/LICENSE[^/]*$' || true; })
odd=$(printf '%s\n' "$assets" | { grep -vE '^[A-Za-z0-9._/-]*$' || true; })
if [ -n "$odd" ]; then
  echo "::error::asset paths keep to letters, digits and ._/-: ${odd//$'\n'/, }"
  exit 1
fi

# Every asset named by its path.
{ git grep -hoE 'res://assets/[A-Za-z0-9._/-]+' -- '*.gd' '*.tscn' '*.tres' '*.godot' '*.cfg' \
  '*.jsonc' || true; } | sed 's#^res://##' > "$named"
# Every buffer and image a named glTF points at, relative to it.
while read -r gltf; do
  dir=$(dirname "$gltf")
  jq -r '((.buffers // []) + (.images // []))[] | .uri // empty' "$gltf" \
    | { grep -v '^data:' || true; } \
    | while read -r uri; do realpath -m --relative-to=. "${dir}/${uri}"; done
done < <(grep '\.gltf$' "$named" || true) >> "$named"
# Every texture extracted from a named model: `<model>_<image>`, generated by its importer.
while read -r model; do
  stem="${model%.*}"
  for imported in "${stem}"_*.import; do
    if [ -f "$imported" ] && grep -q '^generator_parameters=' "$imported"; then
      echo "${imported%.import}"
    fi
  done
done < <(grep -E '\.(glb|gltf)$' "$named" || true) >> "$named"
sort -u -o "$named" "$named"

unused=$(printf '%s\n' "$assets" | { grep -vxFf "$named" || true; } | { grep -v '^$' || true; })
if [ -n "$unused" ]; then
  while read -r file; do
    echo "::error file=${file}::${file} is in the repository but nothing uses it"
  done <<< "$unused"
  exit 1
fi
