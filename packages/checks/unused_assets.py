"""Fails on assets that nothing uses (#320). A file under assets/ is used when its res:// path is
named in a script, scene, resource, content file or the project settings; when a used glTF names
it as one of its buffers or images; or when it's a texture Godot's import extracted from a used
model next to it (named `<model>_<image>`, its .import carrying the generating importer's
parameters). Each pack's own notes (SOURCE.md, its license) and Godot's .import files are left
out: they come with the files they describe. Asset paths keep to letters, digits and `._/-`, so
a path is always matched whole.

    uv run --locked packages/checks/unused_assets.py
"""

import glob
import json
import os
import re
import sys
from pathlib import Path

from annotations import error
from git_files import git_files

NOTES = re.compile(r".*\.import|.*/SOURCE\.md|.*/LICENSE[^/]*")
PLAIN = re.compile(r"[A-Za-z0-9._/-]*")
NAMED = re.compile(rb"res://(assets/[A-Za-z0-9._/-]+)")
NAMING = ("*.gd", "*.tscn", "*.tres", "*.godot", "*.cfg", "*.jsonc")


def gltf_files(gltf: str) -> set[str]:
    """Every buffer and image the glTF points at, relative to the repository's root."""
    document = json.loads(Path(gltf).read_text(encoding="utf-8"))
    uris = [
        entry["uri"]
        for entry in document.get("buffers", []) + document.get("images", [])
        if entry.get("uri")
    ]
    # Joined as text and resolved like `realpath -m`: an absolute-looking URI stays under the
    # glTF's folder, and symlinks resolve.
    folder = os.path.dirname(gltf)
    return {
        os.path.relpath(os.path.realpath(f"{folder}/{uri}"))
        for uri in uris
        if not uri.startswith("data:")
    }


def extracted_textures(model: str) -> set[str]:
    """Every texture Godot's import extracted from the model: `<model>_<image>`, generated by its
    importer."""
    stem = os.path.splitext(model)[0]
    return {
        imported.removesuffix(".import")
        for imported in glob.glob(f"{glob.escape(stem)}_*.import")
        if os.path.isfile(imported)
        and any(
            line.startswith("generator_parameters=")
            for line in Path(imported).read_text(encoding="utf-8").split("\n")
        )
    }


def main() -> int:
    # The game's project folder (#1101): every path below is relative to it.
    os.chdir(Path(__file__).resolve().parents[1] / "game")
    assets = [path for path in git_files("assets") if not NOTES.fullmatch(path)]
    odd = [path for path in assets if not PLAIN.fullmatch(path)]
    if odd:
        print(f"::error::asset paths keep to letters, digits and ._/-: {', '.join(odd)}")
        return 1

    # Every asset named by its path.
    named = {
        match.decode()
        for file in git_files(*NAMING)
        for match in NAMED.findall(Path(file).read_bytes())
    }
    models = sorted(path for path in named if path.endswith((".glb", ".gltf")))
    for model in models:
        if model.endswith(".gltf") and not os.path.isfile(model):
            print(f"::error::{model} is named, but there is no such file to read its files from")
            return 1
        if model.endswith(".gltf"):
            named |= gltf_files(model)
        named |= extracted_textures(model)

    unused = [path for path in assets if path not in named]
    for path in unused:
        print(error(path, f"{path} is in the repository but nothing uses it"))
    return 1 if unused else 0


if __name__ == "__main__":
    sys.exit(main())
